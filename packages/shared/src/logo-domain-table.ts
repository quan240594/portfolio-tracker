/**
 * Curated table of ticker -> official website domain, used only to ask an icon service for the logo that identifies a holding.
 * Domains are facts, not artwork: no logo file lives in the repository. Only domains that are certain are listed; a missing or
 * wrong entry is fixed by the owner through the `domain` field of the classification override (see logo-domains.ts).
 *
 * Keys are the ticker as the app writes it without the exchange suffix (`BRK-B`, `NOVO-B`). The group says on which market the
 * ticker lives, because tickers collide across markets (`MRK` is Merck & Co in the US and Merck KGaA on Xetra, `SAN` is Sanofi in
 * Paris and Santander in Madrid). A symbol is looked up in the group of its own suffix first, then in the US group (cross-listings
 * such as `AAPL.DE` carry the US ticker).
 */
export type DomainTable = Readonly<Record<string, string>>;

